/* 타일 견본 — 런처보드·바로가기에서 실제로 보이는 그 모양 */
function hTile(o) {
  return '<span class="tile">' + hSvg(o.icon, o.color)
    + '<span class="tx"><b>' + o.t + (o.v ? '<em>' + o.v + '</em>' : '') + '</b>'
    + '<i>' + (o.sub || 'script.google.com') + '</i></span>'
    + (o.star !== undefined ? '<span class="star' + (o.star ? ' on' : '') + '">'
        + (o.star ? '★' : '☆') + '</span>' : '')
    + (o.mine ? '<span class="mine">나만</span>' : '') + '</span>';
}
